import AppKit

/// Small "Orca <name>.app" bundles in ~/Applications/Barnacles, so each
/// barnacle can be found in Spotlight and kept in the Dock.
enum Launcher {
    static var folder: URL {
        FileManager.default.homeDirectoryForCurrentUser
            .appendingPathComponent("Applications/Barnacles", isDirectory: true)
    }

    static func url(forName name: String) -> URL {
        let safe = name.replacingOccurrences(of: "/", with: "-").replacingOccurrences(of: ":", with: "-")
        return folder.appendingPathComponent("Orca \(safe).app", isDirectory: true)
    }

    static func write(for barnacle: Barnacle) throws -> URL {
        let fm = FileManager.default
        let app = url(forName: barnacle.name)
        let contents = app.appendingPathComponent("Contents")
        try? fm.removeItem(at: app)
        try fm.createDirectory(at: contents.appendingPathComponent("MacOS"), withIntermediateDirectories: true)

        let plist: [String: Any] = [
            "CFBundleName": "Orca \(barnacle.name)",
            "CFBundleDisplayName": "Orca \(barnacle.name)",
            "CFBundleIdentifier": "dev.barnacles.launcher.\(barnacle.id)",
            "CFBundleExecutable": "launch",
            "CFBundlePackageType": "APPL",
            "CFBundleShortVersionString": "1.0",
            "CFBundleInfoDictionaryVersion": "6.0",
            "LSUIElement": true,
        ]
        let plistData = try PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0)
        try plistData.write(to: contents.appendingPathComponent("Info.plist"))

        // Finds Orca by bundle id when clicked, so it survives Orca updates. If
        // this barnacle is already running, Orca brings its window forward.
        // If Orca can't be opened (usually because it isn't installed), the
        // launcher says so instead of silently doing nothing.
        let script = """
        #!/bin/sh
        # Generated by Barnacles for "\(barnacle.name)".
        /usr/bin/open -n -b \(Orca.bundleID) --args '\(Orca.userDataFlag)\(barnacle.folder.path)' && exit 0

        answer=$(/usr/bin/osascript -e 'button returned of (display dialog "Orca could not be opened. It may not be installed. Install Orca, then try again." with title "Barnacles" buttons {"Cancel", "Get Orca"} default button "Get Orca" with icon caution)' 2>/dev/null)
        [ "$answer" = "Get Orca" ] && exec /usr/bin/open '\(Orca.website.absoluteString)'
        exit 1

        """
        let scriptURL = contents.appendingPathComponent("MacOS/launch")
        try script.write(to: scriptURL, atomically: true, encoding: .utf8)
        try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: scriptURL.path)

        NSWorkspace.shared.setIcon(icon(for: barnacle), forFile: app.path, options: [])
        return app
    }

    /// Rewrites a barnacle's launcher if it has one, so launchers made by older
    /// versions (or the command-line tool) get the current script.
    static func refreshIfPresent(for barnacle: Barnacle) {
        guard FileManager.default.fileExists(atPath: url(forName: barnacle.name).path) else { return }
        _ = try? write(for: barnacle)
    }

    static func remove(for barnacle: Barnacle) {
        let app = url(forName: barnacle.name)
        if FileManager.default.fileExists(atPath: app.path) {
            try? FileManager.default.trashItem(at: app, resultingItemURL: nil)
        }
    }

    /// Orca's icon with a colored badge showing the barnacle's initial.
    static func icon(for barnacle: Barnacle) -> NSImage {
        let base: NSImage = Orca.appURL.map { NSWorkspace.shared.icon(forFile: $0.path) }
            ?? NSImage(systemSymbolName: "app.fill", accessibilityDescription: nil)
            ?? NSImage()
        let initial = String(barnacle.name.trimmingCharacters(in: .whitespaces).prefix(1)).uppercased()
        let color = barnacle.color.nsColor

        return NSImage(size: NSSize(width: 512, height: 512), flipped: false) { rect in
            base.draw(in: rect)
            let d = rect.width * 0.44
            let badge = NSRect(x: rect.maxX - d - rect.width * 0.03, y: rect.minY + rect.width * 0.04,
                               width: d, height: d)
            NSColor.white.setFill()
            NSBezierPath(ovalIn: badge.insetBy(dx: -d * 0.07, dy: -d * 0.07)).fill()
            color.setFill()
            NSBezierPath(ovalIn: badge).fill()

            var font = NSFont.systemFont(ofSize: d * 0.56, weight: .bold)
            if let rounded = font.fontDescriptor.withDesign(.rounded) {
                font = NSFont(descriptor: rounded, size: d * 0.56) ?? font
            }
            let text = NSAttributedString(string: initial, attributes: [
                .font: font, .foregroundColor: NSColor.white,
            ])
            let size = text.size()
            text.draw(at: NSPoint(x: badge.midX - size.width / 2, y: badge.midY - size.height / 2))
            return true
        }
    }
}
